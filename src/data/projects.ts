export type ProjectSlug = (typeof projects)[number]["slug"];

/** Section ids declared for one project; `never` when it has no sections. */
export type ProjectSectionId<S extends ProjectSlug> =
  Extract<(typeof projects)[number], { slug: S }> extends { sections: readonly (infer Id extends string)[] }
    ? Id
    : never;

export const projectCategories = ["next-app", "wp-plugin", "wp-theme", "live-site", "system"] as const;

/** One entry per public site; plugins that run on another project's site are excluded. */
export const liveSites = projects.flatMap((project) =>
  "liveUrl" in project && project.category !== "wp-plugin"
    ? [{ slug: project.slug, url: project.liveUrl, host: new URL(project.liveUrl).hostname.replace(/^www\./, "") }]
    : [],
);

export function projectCover(slug: string) {
  return `/images/projects/${slug}.webp`;
}

export function projectSectionImage(slug: string, sectionId: string) {
  return `/images/projects/${slug}/${sectionId}.webp`;
}
